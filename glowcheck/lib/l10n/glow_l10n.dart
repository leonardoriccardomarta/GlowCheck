typedef GlowLocaleSetter = Future<void> Function(String code);

class GlowLang {
  const GlowLang({
    required this.code,
    required this.nativeName,
    required this.flag,
  });

  final String code;
  final String nativeName;
  final String flag;
}

class GlowL10n {
  GlowL10n._();

  static const supported = [
    GlowLang(code: 'it', nativeName: 'Italiano', flag: 'IT'),
    GlowLang(code: 'en', nativeName: 'English', flag: 'EN'),
    GlowLang(code: 'es', nativeName: 'Español', flag: 'ES'),
    GlowLang(code: 'fr', nativeName: 'Français', flag: 'FR'),
    GlowLang(code: 'de', nativeName: 'Deutsch', flag: 'DE'),
  ];

  static const supportedLocales = [
    Locale('it'),
    Locale('en'),
    Locale('es'),
    Locale('fr'),
    Locale('de'),
  ];

  static String currentCode = 'it';
  static GlowLocaleSetter? persistLocale;

  static String normalize(String? code) {
    final value = (code ?? 'it').toLowerCase();
    return supported.any((item) => item.code == value) ? value : 'it';
  }

  static GlowLang currentLang([String? code]) {
    final value = normalize(code ?? currentCode);
    return supported.firstWhere((item) => item.code == value);
  }

  static String t(String key, [Map<String, String>? vars]) {
    final locale = normalize(currentCode);
    var text = _tables[locale]?[key] ?? _tables['it']?[key] ?? key;
    vars?.forEach((name, value) {
      text = text.replaceAll('{$name}', value);
    });
    return text;
  }

  static Future<void> pick(BuildContext context) {
    return Navigator.of(context, rootNavigator: true).push(
      MaterialPageRoute(builder: (_) => const LanguageScreen()),
    );
  }
}

class GlowLanguageButton extends StatelessWidget {
  const GlowLanguageButton({
    super.key,
    this.light = false,
  });

  final bool light;

  @override
  Widget build(BuildContext context) {
    final lang = GlowL10n.currentLang();
    final color = light ? const Color(0xFFF7F4EF) : const Color(0xFF1C1917);
    return GestureDetector(
      behavior: HitTestBehavior.opaque,
      onTap: () => GlowL10n.pick(context),
      child: ConstrainedBox(
        constraints: const BoxConstraints(minHeight: 44, minWidth: 96),
        child: Padding(
          padding: const EdgeInsets.symmetric(horizontal: 8, vertical: 8),
          child: Row(
            mainAxisSize: MainAxisSize.min,
            mainAxisAlignment: MainAxisAlignment.end,
            children: [
              Text(
                lang.nativeName,
                style: TextStyle(
                  color: color,
                  fontWeight: FontWeight.w700,
                  fontSize: 13,
                ),
              ),
              const SizedBox(width: 2),
              Icon(Icons.expand_more_rounded, size: 18, color: color),
            ],
          ),
        ),
      ),
    );
  }
}

